function coilOf(input: {
  id: string;
  slug: string;
  archiveId: string;
  brandId: string;
  name: string;
  familyId: string;
  subId: string;
  platformIds: string[];
  ohms: number;
  wattMin: number;
  wattMax: number;
  draws: Draw[];
  connector: Coil["connector"];
  wire: string;
  summary: string;
  sourceLabel: string;
  sourceUrl: string;
  caveats: string[];
  pack: string;
}): Coil {
  return {
    domain: "coil",
    id: input.id,
    slug: input.slug,
    archiveId: input.archiveId,
    brandId: input.brandId,
    name: input.name,
    familyId: input.familyId,
    subId: input.subId,
    summary: input.summary,
    confidence: "fabricante",
    sources: [{ label: input.sourceLabel, url: input.sourceUrl }],
    caveats: input.caveats,
    tags: [...input.draws.map((d) => d.toLowerCase()), `${input.ohms}ohm`, input.brandId],
    status: "referenciado",
    platformIds: input.platformIds,
    ohms: input.ohms,
    wattMin: input.wattMin,
    wattMax: input.wattMax,
    wire: input.wire,
    build: "Malla",
    draws: input.draws,
    connector: input.connector,
    refillable: true,
    pack: input.pack,
  };
}

