import type { Liquid, LiquidVariation, Ratio } from "./types.ts";

interface DrifterProduct {
  flavor: string;
  code: string;
  handle: string;
  ratio: Ratio;
  flavorIds: string[];
  blurb: string;
  extraCaveats?: string[];
}

const consulted = "consultado 2026-09-29";

const source = (title: string, handle: string): Liquid["sources"] => [
  {
    label: `Drifter — ${title} (${consulted})`,
    url: `https://driftervape.com/products/${handle}`,
  },
];

const noUfi =
  "No se reproduce número de notificación TPD ni código UFI: no constan en la ficha consultada.";

function composition(ratio: Ratio): LiquidVariation["composition"] {
  const [vg, pg] = ratio.split("/").map(Number) as [number, number];
  return { vgPct: vg, pgPct: pg };
}

function saltProduct(p: DrifterProduct): Liquid {
  const slug = `drifter-${p.code}-sales`;
  return {
    domain: "liquid",
    id: slug,
    slug,
    archiveId: `A510-LIQ-DRF-${p.code.toUpperCase()}-SALES`,
    brandId: "drifter",
    name: p.flavor,
    line: "Bar Salts",
    genreId: "sales",
    summary: `Bar Salts sabor ${p.flavor}: ${p.blurb} La web oficial lo declara bote de 10 ml y ratio ${p.ratio}, en graduaciones de 10 y 20 mg/ml.`,
    confidence: "fabricante",
    sources: source(`${p.flavor} 10ml`, p.handle),
    caveats: [
      "La web oficial publica 10 mg/ml y 20 mg/ml; no lista 5 mg/ml.",
      noUfi,
      ...(p.extraCaveats ?? []),
    ],
    tags: ["sales", "10ml", "10mg", "20mg", "drifter", "bar-salts", p.ratio],
    status: "referenciado",
    flavorIds: p.flavorIds,
    draws: ["MTL", "RDL"],
    variations: [10, 20].map((mg): LiquidVariation => ({
      id: `${slug}-${mg}`,
      label: `${mg} mg/ml · 10 ml`,
      volumeMl: 10,
      hasNicotine: true,
      nicotineMg: mg,
      ratio: p.ratio,
      bottle: "Bote de 10 ml listo para vapear",
      assumedBottleMl: 10,
      tpd: "si",
      composition: composition(p.ratio),
    })),
  };
}

function shortfillProduct(p: DrifterProduct): Liquid {
  const slug = `drifter-${p.code}-shortfill`;
  return {
    domain: "liquid",
    id: slug,
    slug,
    archiveId: `A510-LIQ-DRF-${p.code.toUpperCase()}-SHORTFILL`,
    brandId: "drifter",
    name: p.flavor,
    line: "Bar Juice",
    genreId: "shortfill",
    summary: `Bar Juice sabor ${p.flavor}: ${p.blurb} La web oficial lo declara shortfill de 120 ml sin nicotina y ratio ${p.ratio}, con espacio para shots.`,
    confidence: "fabricante",
    sources: source(`${p.flavor} 120ml Shortfill`, p.handle),
    caveats: [
      "La web lo describe como shortfill sin nicotina con espacio para shots; no usa la expresión «doble concentrado».",
      "No se publica el reparto entre líquido y hueco libre ni cuántos shots admite el bote.",
      noUfi,
      ...(p.extraCaveats ?? []),
    ],
    tags: ["shortfill", "120ml", "0mg", "drifter", "bar-juice", p.ratio],
    status: "referenciado",
    flavorIds: p.flavorIds,
    draws: ["MTL", "RDL", "DL"],
    variations: [
      {
        id: `${slug}-0`,
        label: "120 ml · 0 mg/ml",
        volumeMl: 120,
        hasNicotine: false,
        ratio: p.ratio,
        bottle: "Shortfill de 120 ml sin nicotina, con espacio para shots",
        tpd: "no",
        composition: composition(p.ratio),
      },
    ],
  };
}

